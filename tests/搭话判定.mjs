// 陪看「自己开口」的判定 —— 纯函数，不碰真实会话
// ⭐ 0.0.8：间隔单位从「分钟」改成「秒」；老的间隔分钟还认。
// ⭐ 0.2.4：不传「浮」时是**范围内真随机**（20~120 秒那一档）；
//   要测「到点/没到点」这种确定性的事，就传 浮（0.5 = 原来的固定间隔）。
import { 要搭话 } from '../lib/host.js'

let 挂 = 0
const 报 = (名, 过, 附) => { if (!过) 挂++; console.log((过 ? 'PASS ' : 'FAIL ') + 名 + (过 ? '' : '  ← ' + (附 || ''))) }
const 现在 = 1000000
const 定 = { 浮: 0.5 }   // 确定性：有效间隔 = 设定值

报('关着（间隔 0 秒）永远不开口', 要搭话({ 间隔秒: 0, 有字幕: true, 现在, 骰子: 0 }) === false)
报('没字幕（像对着黑屏）不开口', 要搭话({ 间隔秒: 600, 有字幕: false, 现在, 骰子: 0 }) === false)
报('刚说过（没到间隔）不开口', 要搭话({ ...定, 间隔秒: 600, 有字幕: true, 上次: 现在 - 60 * 1000, 现在, 骰子: 0 }) === false)
报('到点了但骰子没中 → 不开口',
  要搭话({ ...定, 间隔秒: 600, 有字幕: true, 上次: 现在 - 660 * 1000, 现在, 骰子: 0.9, 概率: 0.35 }) === false)
报('到点 + 骰子中了 → 开口',
  要搭话({ ...定, 间隔秒: 600, 有字幕: true, 上次: 现在 - 660 * 1000, 现在, 骰子: 0.1, 概率: 0.35 }) === true)
报('从没说过（上次 0）也算到点', 要搭话({ ...定, 间隔秒: 600, 有字幕: true, 上次: 0, 现在, 骰子: 0 }) === true)
报('概率 0 时永远不中', 要搭话({ ...定, 间隔秒: 600, 有字幕: true, 现在, 骰子: 0, 概率: 0 }) === false)
报('概率 1 时一定中', 要搭话({ ...定, 间隔秒: 600, 有字幕: true, 现在, 骰子: 0.999, 概率: 1 }) === true)

// 秒这个单位真的生效：间隔 30 秒，过了 31 秒就该算到点
报('30 秒的间隔：31 秒之后算到点',
  要搭话({ ...定, 间隔秒: 30, 有字幕: true, 上次: 现在 - 31 * 1000, 现在, 骰子: 0 }) === true)
报('30 秒的间隔：29 秒还没到',
  要搭话({ ...定, 间隔秒: 30, 有字幕: true, 上次: 现在 - 29 * 1000, 现在, 骰子: 0 }) === false)
// 老配置的「分钟」还认得（10 分钟 = 600 秒）
报('老配置（间隔分钟 10）也还算数',
  要搭话({ ...定, 间隔分钟: 10, 有字幕: true, 上次: 现在 - 601 * 1000, 现在, 骰子: 0 }) === true)

// ⭐ 0.2.4：真随机那一档 —— 把 Math.random 钉死，看间隔落在哪儿。
//   （不能靠「多跑几次取最小」来测：每次试探都会重新掷一次，测出来会偏小。）
{
  const 到点秒 = (r) => {
    const 原 = Math.random
    Math.random = () => r
    try {
      for (let 秒 = 1; 秒 <= 400; 秒++) {
        if (要搭话({ 间隔秒: 15, 有字幕: true, 上次: 现在 - 秒 * 1000, 现在, 骰子: 0, 概率: 1 })) return 秒
      }
      return -1
    } finally {
      Math.random = 原
    }
  }
  报('随机间隔：掷到最小 → 15 秒（就是你填的那个数）', 到点秒(0) === 15, '得到 ' + 到点秒(0))
  报('随机间隔：掷到最大 → 120 秒', 到点秒(0.999999) === 120, '得到 ' + 到点秒(0.999999))
  报('随机间隔：掷到中间 → 约 68 秒（不是 15 那种固定值）', Math.abs(到点秒(0.5) - 68) <= 1, '得到 ' + 到点秒(0.5))
}

console.log('\n共 14 项，失败 ' + 挂 + ' 项')
process.exitCode = 挂 ? 1 : 0
